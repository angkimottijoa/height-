"""
Pull the user's catenary poles out of a Bedrock world and write them as the
railway tool's built-in poles (packs/ArceonDLC_BP/scripts/lib/pole_data.js).

    python3 tools/arceon_dlc/extract_poles.py <world>/db

Structures (saved with a structure block, "save to memory"):
  mystructure:1 / :2 / :3  gantries for 1 / 2 / 3 tracks, track along +x,
                           the pole itself in the x = 1 slice; x = 0 and 2 hold
                           the wire ends (buttons, with barriers holding them)
  mystructure:야           a single post (x = 0 slice), for feeder wires only
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from bedrock_world import load, read_nbt

HERE = os.path.dirname(os.path.abspath(__file__))
DEFS = json.load(open(os.path.join(HERE, 'jstest', 'defs.json')))
OUT = os.path.join(HERE, '..', '..', 'packs', 'ArceonDLC_BP', 'scripts', 'lib', 'pole_data.js')
CH = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
SKIP = {'minecraft:air', 'minecraft:structure_block', 'minecraft:structure_void'}


def states(name, st):
    """NBT stores booleans as bytes: give the script API real booleans."""
    d = DEFS.get(name, {})
    out = {}
    for k, v in st.items():
        vals = d.get(k)
        if vals and isinstance(vals[0], bool):
            v = bool(v)
        out[k] = v
    return out


def pole(db, name, plane, wires):
    t = read_nbt(db[('structuretemplate_mystructure:' + name).encode()])
    X, Y, Z = t['size']
    st = t['structure']
    pal = st['palette']['default']['block_palette']
    idx = st['block_indices'][0]
    at = lambda x, y, z: idx[(x * Y + y) * Z + z]
    used, palette, rows = {}, [], []
    for y in range(Y):
        row = ''
        for z in range(Z):
            i = at(plane, y, z)
            p = pal[i] if i >= 0 else None
            if not p or p['name'] in SKIP:
                row += '.'
                continue
            key = json.dumps([p['name'], p['states']], sort_keys=True)
            if key not in used:
                used[key] = CH[len(palette)]
                palette.append({'name': p['name'], 'states': states(p['name'], p['states'])})
            row += used[key]
        rows.append(row)
    while rows and set(rows[-1]) == {'.'}:
        rows.pop()
    centre = (Z - 1) // 2
    anchors = []
    for x in wires:
        for y in range(Y):
            for z in range(Z):
                i = at(x, y, z)
                if i >= 0 and pal[i]['name'].endswith('_button'):
                    a = [z - centre, y, 'hang' if pal[i]['states'].get('facing_direction') == 0 else 'lie']
                    if a not in anchors:
                        anchors.append(a)
    anchors.sort()
    return {'w': Z, 'centre': centre, 'palette': palette, 'rows': rows, 'anchors': anchors}


def main(dbdir):
    db = load(dbdir)
    data = {n: pole(db, n, 1, [0, 2]) for n in ('1', '2', '3')}
    single = pole(db, '야', 0, [])
    # the single post carries feeder wires from its top (the heavy cores), like the gantry posts
    single['anchors'] = [[z - single['centre'], y, 'lie'] for y, r in enumerate(single['rows']) for z, c in enumerate(r)
                         if c != '.' and single['palette'][CH.index(c)]['name'] == 'minecraft:heavy_core']
    data['post'] = single
    js = ('// Generated by tools/arceon_dlc/extract_poles.py from the user\'s world: do not edit by hand.\n'
          '// rows[y] across the track (index - centre = sideways offset), one char per block, "." = nothing;\n'
          '// built with the track running east (+x). anchors: [sideways, height, "hang" | "lie"] wire ends.\n'
          'export const POLES = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
    open(OUT, 'w').write(js)
    for n, p in data.items():
        print(n, 'width', p['w'], 'height', len(p['rows']), 'palette', len(p['palette']), 'anchors', len(p['anchors']))


if __name__ == '__main__':
    main(sys.argv[1])
