"""Pre-rasterize Arceon's text-tool fonts into JS modules for the add-on.

Bedrock scripts cannot read TTF files, so every glyph is drawn here once
(1-bit, no anti-aliasing, like Java AWT's default drawString) and written to
packs/ArceonDLC_BP/scripts/fonts/<font>.js. tools/text.js imports a module
lazily and scales the bitmaps to the size the player asks for.

    python3 tools/arceon_dlc/gen_fonts.py <arceon fonts dir> packs/ArceonDLC_BP/scripts/fonts \
        [--hangul /usr/share/fonts/truetype/wqy/wqy-zenhei.ttc]

Arceon's fonts dir is the jar's fonts/ folder (comicsans.ttf ... verdana.ttf).
Every font gets printable ASCII + Latin-1 at a 48 px em. 'unicode' (MS Mincho
in Arceon) also gets Greek/Cyrillic at 48 px and, at a 22 px em, CJK
punctuation, kana, full-width forms and CJK ideographs (unicode_han.js).
MS Mincho has no Hangul, so Hangul syllables and jamo come from the --hangul
font (WenQuanYi Zen Hei by default, GPL with font embedding exception) and go
to unicode_hangul.js.

Module format:
    export default {name, em, sets: [{em, glyphs: {codepoint: 'adv,x,y,w,h,base64'}}]}
  adv      advance in px at that em
  x, y     bitmap offset from the pen position on the baseline (y < 0 is up)
  w, h     bitmap size; bits are row-major, MSB first, base64 encoded
"""
import argparse
import base64
import os
import sys

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

LATIN_EM = 48
CJK_EM = 22

FONTS = ['comicsans.ttf', 'georgia.ttf', 'impact.ttf', 'king.ttf', 'lobster.otf', 'medieval.ttf',
         'minecraft.ttf', 'papyrus.ttf', 'trebuchet.ttf', 'unicode.ttf', 'verdana.ttf']

LATIN = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
GREEK_CYRILLIC = list(range(0x100, 0x530))  # Latin Extended, IPA, Greek, Cyrillic: whatever the font has
CJK_SMALL = (list(range(0x3000, 0x3040)) + list(range(0x3040, 0x3100)) + list(range(0x31F0, 0x3200))
             + list(range(0xFF00, 0xFFF0)))
HAN = list(range(0x4E00, 0xA000))
HANGUL = list(range(0xAC00, 0xD7A4)) + list(range(0x1100, 0x1200)) + list(range(0x3130, 0x3190))


def cmap_of(path, index=0):
    kw = {'fontNumber': index} if path.lower().endswith('.ttc') else {}
    return TTFont(path, lazy=True, **kw).getBestCmap()


def raster(font, ch, em):
    """(adv, x, y, w, h, bits-bytes) for one character."""
    adv = int(round(font.getlength(ch)))
    pad = em * 2
    size = (em * 4 + adv, em * 4)
    img = Image.new('L', size, 0)
    d = ImageDraw.Draw(img)
    d.fontmode = '1'
    d.text((pad, pad * 1), ch, font=font, fill=255, anchor='ls')
    box = img.getbbox()
    if not box:
        return adv, 0, 0, 0, 0, b''
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    px = img.load()
    out = bytearray((w * h + 7) // 8)
    i = 0
    for yy in range(y0, y1):
        for xx in range(x0, x1):
            if px[xx, yy] >= 128:
                out[i >> 3] |= 0x80 >> (i & 7)
            i += 1
    return adv, x0 - pad, y0 - pad, w, h, bytes(out)


def glyph_set(path, codes, em, index=0):
    cm = cmap_of(path, index)
    font = ImageFont.truetype(path, size=em, index=index, layout_engine=ImageFont.Layout.BASIC)
    glyphs = {}
    for c in codes:
        if c not in cm:
            continue
        adv, x, y, w, h, bits = raster(font, chr(c), em)
        glyphs[c] = f'{adv},{x},{y},{w},{h},{base64.b64encode(bits).decode()}'
    return glyphs


def write(out_dir, name, em, sets, src):
    body = ','.join(
        '{em:%d,glyphs:{%s}}' % (e, ','.join(f'{c}:"{g}"' for c, g in sorted(gl.items()))) for e, gl in sets)
    path = os.path.join(out_dir, name + '.js')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(f'// GENERATED by tools/arceon_dlc/gen_fonts.py from {src} -- do not edit by hand.\n')
        fh.write(f'export default {{name:"{name}",em:{em},sets:[{body}]}};\n')
    n = sum(len(gl) for _, gl in sets)
    print(f'  {name}.js  {n} glyphs  {os.path.getsize(path) / 1024:.0f} KB')
    return os.path.getsize(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('fonts')
    ap.add_argument('out')
    ap.add_argument('--hangul', default='/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc')
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    total = 0
    for f in FONTS:
        path = os.path.join(a.fonts, f)
        name = os.path.splitext(f)[0]
        sets = [(LATIN_EM, glyph_set(path, LATIN + (GREEK_CYRILLIC if name == 'unicode' else []), LATIN_EM))]
        if name == 'unicode':
            sets.append((CJK_EM, glyph_set(path, CJK_SMALL, CJK_EM)))
            total += write(a.out, 'unicode_han', CJK_EM, [(CJK_EM, glyph_set(path, HAN, CJK_EM))], f)
            if sum(1 for c in cmap_of(path) if 0xAC00 <= c <= 0xD7A3) == 0:
                print(f'  note: {f} has no Hangul; using {os.path.basename(a.hangul)}')
            hg = glyph_set(a.hangul, HANGUL, CJK_EM)
            if not hg:
                sys.exit('no Hangul glyphs found in ' + a.hangul)
            total += write(a.out, 'unicode_hangul', CJK_EM, [(CJK_EM, hg)], os.path.basename(a.hangul))
        total += write(a.out, name, LATIN_EM, sets, f)
    print(f'total {total / 1024 / 1024:.2f} MB')


if __name__ == '__main__':
    main()
